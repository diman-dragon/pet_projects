function getDocumentWord(count: number) {
  if (count === 1) return 'документ';
  if (count < 5) return 'документа';
  return 'документов';
}

export function getAISummaryFallback(query: string, count: number): string {
  if (!query || count === 0) {
    return '';
  }

  const lower = query.toLowerCase();
  for (const [key, summary] of Object.entries(AI_SUMMARIES)) {
    if (lower.includes(key)) {
      return summary;
    }
  }

  return `По вашему запросу найдено ${count} ${getDocumentWord(count)} из баз ЕСПЧ и внутренних архивов. Для более точного анализа уточните запрос — добавьте номер статьи, юрисдикцию или ключевые обстоятельства дела.`;
}
