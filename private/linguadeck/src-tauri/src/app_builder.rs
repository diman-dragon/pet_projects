pub fn build() -> tauri::Builder<tauri::Wry> {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_fs::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_sql::Builder::default().build())
        .invoke_handler(tauri::generate_handler![
            crate::commands::deck_list,
            crate::commands::deck_dashboard_stats,
            crate::commands::deck_create,
            crate::commands::deck_update,
            crate::commands::deck_delete,
            crate::commands::card_list,
            crate::commands::card_create,
            crate::commands::card_create_batch,
            crate::commands::card_update,
            crate::commands::card_get,
            crate::commands::card_delete,
            crate::commands::card_delete_many,
            crate::commands::card_stats,
            crate::commands::settings_get,
            crate::commands::settings_save,
            crate::commands::log_write,
            crate::commands::log_list,
            crate::commands::log_clear,
            crate::commands::view_log,
            crate::commands::study_session_cards,
            crate::commands::study_auto_review_card,
            crate::commands::study_forecast,
            crate::commands::study_cards_for_day,
            crate::commands::views_for_day,
            crate::commands::activity_history,
            crate::commands::day_stats,
            crate::commands::streak,
            crate::commands::grammar_dashboard,
            crate::commands::grammar_unit_list,
            crate::commands::grammar_unit_create,
            crate::commands::grammar_unit_update,
            crate::commands::grammar_unit_delete,
            crate::commands::grammar_exercise_list,
            crate::commands::grammar_exercise_save,
            crate::commands::grammar_practice,
            crate::commands::grammar_session_complete,
            crate::commands::grammar_check_unit,
            crate::commands::grammar_linked_cards,
            crate::commands::grammar_units_for_card
        ])
}
