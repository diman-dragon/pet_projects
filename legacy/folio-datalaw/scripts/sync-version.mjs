// package.json version -> www/js/core/version.js + android versionName/versionCode
import fs from 'node:fs';
const { version } = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const [a, b, c] = version.split('.').map(Number);
const code = a * 1_000_000 + b * 1_000 + c; // 0.0.1 -> 1, 0.1.0 -> 1000, 1.0.0 -> 1000000
fs.writeFileSync('www/js/core/version.js', `// GENERATED by scripts/sync-version.mjs - do not edit\nexport const VERSION = '${version}';\n`);
const g = 'android/app/build.gradle';
const s = fs.readFileSync(g, 'utf8')
  .replace(/versionCode \d+/, `versionCode ${code}`)
  .replace(/versionName "[^"]*"/, `versionName "${version}"`);
fs.writeFileSync(g, s);
console.log(`version ${version} (code ${code})`);
